// parsed lazily into arrays of row strings
const GLYPH_ROWS = {};
for(const ch in GLYPHS) GLYPH_ROWS[ch] = GLYPHS[ch].split(' ');

// ---------------------------------------------------------------------------
// One tiny canvas per (glyph, colour, scale). Drawing text then costs one
// drawImage per character instead of ~20 fillRects.
// ---------------------------------------------------------------------------
const glyphCache = new Map();
function glyphFor(ch, col, scale){
  const key = ch + '\u0000' + col + '\u0000' + scale;
  let cv = glyphCache.get(key);
  if(cv) return cv;
  const rows = GLYPH_ROWS[ch] || GLYPH_ROWS['?'];
  cv = document.createElement('canvas');
  cv.width = FONT_W*scale; cv.height = FONT_H*scale;
  const g = cv.getContext('2d');
  g.imageSmoothingEnabled = false;
  g.fillStyle = col;
  for(let r=0;r<rows.length;r++){
    const row = rows[r];
    let run = 0;
    for(let i=0;i<=FONT_W;i++){
      if(i<FONT_W && row[i]==='1'){ run++; continue; }
      if(run){ g.fillRect((i-run)*scale, r*scale, run*scale, scale); run=0; }
    }
  }
  if(glyphCache.size > 4000) glyphCache.clear();
  glyphCache.set(key, cv);
  return cv;
}

// nominal px size -> integer pixel scale
function fontScale(size){
  if(size<=8)  return 1;
  if(size<=13) return 2;
  if(size<=20) return 3;
  return 5;
}
function textWidth(s, size){
  return String(s).length * FONT_ADV * fontScale(size) - fontScale(size);
}

function drawGlyphs(c, s, x, y, col, scale){
  s = String(s);
  const adv = FONT_ADV*scale;
  for(let i=0;i<s.length;i++){
    const ch = s[i];
    if(ch === ' ') continue;
    c.drawImage(glyphFor(ch, col, scale), x + i*adv, y);
  }
}

// Main entry point. Signature matches the old canvas-text helper so every
// existing call site keeps working.
function text(c, s, x, y, col, size, align){
  s = String(s);
  const scale = fontScale(size||7);
  const w = s.length*FONT_ADV*scale - scale;
  let X = x;
  if(align==='center') X = x - w/2;
  else if(align==='right') X = x - w;
  X = Math.round(X); y = Math.round(y);
  drawGlyphs(c, s, X+scale, y+scale, C.ink, scale);   // drop shadow for contrast
  drawGlyphs(c, s, X, y, col, scale);
}
